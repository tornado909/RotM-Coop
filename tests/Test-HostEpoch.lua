package.preload["UEHelpers"] = function() return {} end
local m = dofile("mod/RotMCoop/Scripts/steam_menu.lua")
local check = m.should_follow_host_epoch
assert(not check(1, 0, "waiting_host", "true", "true"))
assert(not check(1, 0, "playing", "false", "true"))
assert(not check(1, 0, "playing", "true", "false"))
assert(not check(0, 0, "playing", "true", "true"))
assert(not check(1, 1, "playing", "true", "true"))
assert(not check(1, 2, "playing", "true", "true"))
assert(check(2, 1, "playing", "true", "true"))
assert(check(2, 1, "disconnected", "true", "true"))
assert(check(2, 1, "waiting_host", "true", "true"))
assert(not check(1, 0, "disconnected", "true", "true"))
assert(not check(2, 1, "game_no_response", "true", "true"))
assert(check("14", "13", "playing", "true", "true"))
assert(not check("14", "14", "playing", "true", "true"))
local pause = m.should_pause_on_world_change
assert(not pause("0", "Hub", "Arena", "true"))
assert(not pause("123", "", "Hub", "true"))
assert(not pause("123", "Hub", "Hub", "true"))
assert(not pause("123", "Hub", "Arena", "false"))
assert(pause("123", "Hub", "Arena", "true"))
assert(pause("123", "Arena", "MainMenu", "true"))
print("Steam session epoch and portal world-change regression passed")
