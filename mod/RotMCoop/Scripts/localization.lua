function M.language()
    local ok,v=pcall(function()
        local lib=StaticFindObject("/Script/Engine.Default__KismetInternationalizationLibrary")
        return lib:GetCurrentCulture():ToString()
    end)
    if not ok or type(v)~="string" then return "en" end
    v=v:lower()
    if dictionaries[v] then return v end
    return v:match("^[a-z]+") or "en"
end
function M.t(key)
    local d=dictionaries[M.language()]
    return d and d[key] or key
end
function M.validate()
    for lang,d in pairs(dictionaries)do
        for k in pairs(ru)do assert(d[k] and d[k]~="",lang..": "..k)end
    end
    return true
end
return M
